#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*str;
	int		len;

	while (*s1 && ft_strchr(set, *s1))
		s1++;
	len = ft_strlen(s1);
	while (len > 0 && ft_strchr(set, s1[len - 1]))
		len--;
	str = malloc(sizeof(char) * len + 1);
	if (!str)
		return (0);
	ft_memcpy(str, s1, len);
	str[len] = 0;
	return (str);
}

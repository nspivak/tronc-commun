#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	temp;

	i = 0;
	temp = 0;
	while (src[i] != '\0')
		i++;
	temp = i;
	i = 0;
	if (size == 0)
		return (temp);
	while (i < size - 1 && src[i] != '\0')
	{
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (temp);
}
